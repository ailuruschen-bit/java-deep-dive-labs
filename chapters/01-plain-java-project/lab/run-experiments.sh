#!/usr/bin/env bash

(
set -euo pipefail

# Keep the demonstration independent of inherited Java options.
unset CLASSPATH JAVA_TOOL_OPTIONS JDK_JAVA_OPTIONS JDK_JAVAC_OPTIONS _JAVA_OPTIONS

lab_root="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
deployment_root="$lab_root/deployment"

if [[ $# -gt 1 || ( $# -eq 1 && "${1:-}" != "--prepare" ) ]]; then
  echo "Usage: $0 [--prepare]" >&2
  exit 2
fi

java_specification_version="$({ java -XshowSettings:properties -version; } 2>&1 \
  | awk -F ' = ' '/^[[:space:]]*java\.specification\.version = / { print $2 }')"
javac_version="$(javac -version 2>&1)"

if [[ "$java_specification_version" != "21" || ! "$javac_version" =~ ^javac\ 21([.]|$) ]]; then
  echo "This lab requires java and javac from JDK 21." >&2
  echo "Found Java $java_specification_version and $javac_version." >&2
  exit 1
fi

expect_failure() {
  local expected_error="$1"
  local expected_detail="$2"
  shift 2
  local output exit_code

  if output="$("$@" 2>&1)"; then
    echo "The command succeeded, but a failure was expected." >&2
    exit 1
  else
    exit_code=$?
  fi

  printf '%s\nexit code: %s\n' "$output" "$exit_code"
  if [[ "$output" != *"$expected_error"* || "$output" != *"$expected_detail"* ]]; then
    echo "The command failed for an unexpected reason." >&2
    exit 1
  fi
}

clear_application_classes() {
  rm -f -- \
    "$deployment_root/dev/deepdive/app/Main.class" \
    "$deployment_root/dev/deepdive/app/MessageService.class"
}

prepare_dependencies() {
  clear_application_classes
  rm -f -- \
    "$deployment_root/lib001/dev/deepdive/greeting/Greeting.class" \
    "$deployment_root/lib002/dev/deepdive/punctuation/Punctuation.class"

  mkdir -p "$deployment_root/lib001" "$deployment_root/lib002"
  (
    cd "$deployment_root"
    javac -d lib001 \
      ../multiple-classpath/src/greeting/dev/deepdive/greeting/Greeting.java
    javac -d lib002 \
      ../multiple-classpath/src/punctuation/dev/deepdive/punctuation/Punctuation.java
  )
}

if [[ "${1:-}" == "--prepare" ]]; then
  prepare_dependencies
  echo "Prepared two application sources and two external class files in:"
  echo "$deployment_root"
  exit 0
fi

# Remove only the class files generated by these introductory experiments.
rm -f -- \
  "$lab_root/step-1/Main.class" \
  "$lab_root/step-1/out/Main.class" \
  "$lab_root/step-2/out/dev/deepdive/app/Main.class"

echo "1. Compile beside Main.java and run from step-1:"
(
  cd "$lab_root/step-1"
  javac Main.java
  java Main
)

echo
echo "2. Use -d to choose an output directory:"
(
  cd "$lab_root/step-1"
  javac -d out Main.java
)

echo
echo "3. Compile and run the packaged class from step-2/out:"
(
  cd "$lab_root/step-2/out"
  javac dev/deepdive/app/Main.java
  java dev.deepdive.app.Main
)

echo
echo "4. Run from the parent directory and observe the missing main class:"
(
  cd "$lab_root/step-2"
  expect_failure \
    "Could not find or load main class dev.deepdive.app.Main" \
    "ClassNotFoundException: dev.deepdive.app.Main" \
    java dev.deepdive.app.Main
)

echo
echo "5. Stay in step-2 and use -cp out to find the main class:"
(
  cd "$lab_root/step-2"
  java -cp out dev.deepdive.app.Main
)

echo
echo "6. Rebuild the provider's class files and prepare the application sources:"
prepare_dependencies

echo
echo "7. Compile both application sources without a class path and observe the missing packages:"
(
  cd "$deployment_root"
  expect_failure \
    "package dev.deepdive.greeting does not exist" \
    "package dev.deepdive.punctuation does not exist" \
    javac \
      dev/deepdive/app/Main.java \
      dev/deepdive/app/MessageService.java
)

echo
echo "8. Compile both application sources with the dependency class path entries:"
(
  cd "$deployment_root"
  javac -cp 'lib001:lib002' \
    dev/deepdive/app/Main.java \
    dev/deepdive/app/MessageService.java
  [[ -f dev/deepdive/app/Main.class && -f dev/deepdive/app/MessageService.class ]]
)

echo
echo "9. Remove the application class files and compile the sources in reverse order:"
clear_application_classes
(
  cd "$deployment_root"
  javac -cp 'lib001:lib002' \
    dev/deepdive/app/MessageService.java \
    dev/deepdive/app/Main.java
  [[ -f dev/deepdive/app/Main.class && -f dev/deepdive/app/MessageService.class ]]
)

echo
echo "10. Run from deployment with one class path containing three entries:"
(
  cd "$deployment_root"
  application_output="$(java -cp '.:lib001:lib002' dev.deepdive.app.Main)"
  printf '%s\n' "$application_output"
  if [[ "$application_output" != "Hello, classpath!" ]]; then
    echo "The application returned an unexpected greeting." >&2
    exit 1
  fi
)

echo
echo "11. Prefix the class name with lib001 and observe the name mismatch:"
(
  cd "$deployment_root"
  expect_failure \
    "NoClassDefFoundError" \
    "wrong name: dev/deepdive/greeting/Greeting" \
    java -cp . lib001.dev.deepdive.greeting.Greeting
)

echo
echo "12. Omit the lib002 runtime class path entry and observe the missing dependency:"
(
  cd "$deployment_root"
  expect_failure \
    "NoClassDefFoundError: dev/deepdive/punctuation/Punctuation" \
    "ClassNotFoundException: dev.deepdive.punctuation.Punctuation" \
    java -cp '.:lib001' dev.deepdive.app.Main
)

echo
echo "All compilation, execution, and expected-failure checks passed."
)
