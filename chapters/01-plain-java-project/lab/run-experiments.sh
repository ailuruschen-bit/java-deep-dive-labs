#!/usr/bin/env bash

set -euo pipefail

lab_root="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
build_root="$lab_root/build"
deployment_root="$lab_root/deployment"

java_specification_version="$({ java -XshowSettings:properties -version; } 2>&1 \
  | awk -F ' = ' '/^[[:space:]]*java\.specification\.version = / { print $2 }')"

if [[ "$java_specification_version" != "21" ]]; then
  echo "This lab requires Java 21, but found Java $java_specification_version." >&2
  exit 1
fi

if [[ -d "$build_root" ]]; then
  rm -r "$build_root"
fi

if [[ -d "$deployment_root" ]]; then
  rm -r "$deployment_root"
fi

if [[ -f "$lab_root/step-1/Main.class" ]]; then
  rm "$lab_root/step-1/Main.class"
fi

mkdir -p \
  "$build_root/step-1-out" \
  "$build_root/step-2" \
  "$deployment_root/app" \
  "$deployment_root/lib/greeting" \
  "$deployment_root/lib/punctuation"

echo "1. Compile beside the source file and run from the working directory:"
(
  cd "$lab_root/step-1"
  javac Main.java
  java Main
)

echo
echo "2. Inspect the generated bytecode:"
javap -c "$lab_root/step-1/Main.class"

echo
echo "3. Use -d to choose an output directory:"
javac -d "$build_root/step-1-out" "$lab_root/step-1/Main.java"
(cd "$build_root/step-1-out" && java Main)

echo
echo "4. Run a packaged class from a child directory:"
javac \
  -d "$build_root/step-2" \
  "$lab_root/step-2/src/dev/deepdive/app/Main.java"
(cd "$build_root/step-2" && java dev.deepdive.app.Main)

echo
echo "5. Compile classes into separate class path roots:"
javac \
  -d "$deployment_root/lib/punctuation" \
  "$lab_root/multiple-classpath/src/punctuation/dev/deepdive/punctuation/Punctuation.java"

javac \
  -cp "$deployment_root/lib/punctuation" \
  -d "$deployment_root/lib/greeting" \
  "$lab_root/multiple-classpath/src/greeting/dev/deepdive/greeting/Greeting.java"

javac \
  -cp "$deployment_root/lib/greeting:$deployment_root/lib/punctuation" \
  -d "$deployment_root/app" \
  "$lab_root/multiple-classpath/src/app/dev/deepdive/app/Main.java"

echo
echo "6. Run with three explicit class path roots:"
java \
  -cp "$deployment_root/app:$deployment_root/lib/greeting:$deployment_root/lib/punctuation" \
  dev.deepdive.app.Main

echo
echo "7. Run with the CLASSPATH environment variable:"
(
  export CLASSPATH="$deployment_root/app:$deployment_root/lib/greeting:$deployment_root/lib/punctuation"
  java dev.deepdive.app.Main
)

echo
echo "8. Omit one dependency root and observe the expected failure:"
set +e
java \
  -cp "$deployment_root/app:$deployment_root/lib/greeting" \
  dev.deepdive.app.Main
missing_dependency_exit_code=$?
set -e
echo "exit code: $missing_dependency_exit_code"

if [[ $missing_dependency_exit_code -eq 0 ]]; then
  echo "The expected class path failure did not occur." >&2
  exit 1
fi

echo
echo "9. Use the Java 21 single-file source launcher:"
java "$lab_root/step-1/Main.java"
